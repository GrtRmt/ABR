const STORAGE_KEY = 'remaut_blog_posts_v2';

export function getStoredBlogPosts(): BlogPost[] {
  if (typeof window === 'undefined') return INITIAL_BLOG_POSTS;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Error loading blog posts from localStorage:', err);
  }
  return INITIAL_BLOG_POSTS;
}

export function saveStoredBlogPosts(posts: BlogPost[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(posts));
  } catch (err) {
    console.error('Error saving blog posts to localStorage:', err);
  }
}

export function resetStoredBlogPosts(): BlogPost[] {
  if (typeof window !== 'undefined') {
    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch (err) {
      console.error('Error resetting blog posts in localStorage:', err);
    }
  }
  return INITIAL_BLOG_POSTS;
}
